fprintf('  电机: Rs=%.4fΩ, Ld=%.2fmH, Lq=%.2fmH, ψf=%.3fWb\n', Rs, Ld*1e3, Lq*1e3, psi_f);
fprintf('  传动比: %d, 齿轮刚度: %.0e N·m/rad\n', i_ratio, k_g);
