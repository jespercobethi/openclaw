%% setup_params.m
%  双驱变桨伺服系统仿真参数定义
%  项目：基于多电机驱动的大型风电变桨伺服系统研究
%  日期：2026-05-28
%  说明：运行此脚本将所有参数加载到 workspace

%% ==================== PMSM 电机参数 ====================
%  来源：李晓凤(2019) + 几何计算
Rs  = 0.03139;      % 定子电阻 [Ω]
Ld  = 3.55e-3;      % d轴电感 [H]
Lq  = 3.72e-3;      % q轴电感 [H]
psi_f = 0.348;       % 永磁体磁链 [Wb]
J_m = 0.26;          % 电机转动惯量 [kg·m²]
B_m = 0.012;         % 电机阻尼系数 [N·m·s/rad]
p   = 3;             % 极对数

%% ==================== 传动机构参数 ====================
%  来源：李奔(2026) + 估算
i_ratio = 800;        % 减速比
k_g = 2e5;            % 齿轮啮合刚度 [N·m/rad]
c_g = 500;            % 齿轮啮合阻尼 [N·m·s/rad]
J_blade = 8000;       % 叶片转动惯量 [kg·m²]
B_blade = 50;         % 叶片阻尼系数 [N·m·s/rad]

%% ==================== 风力机参数 ====================
R_blade = 45;          % 叶片长度 [m]
rho = 1.225;           % 空气密度 [kg/m³]
A = pi * R_blade^2;    % 扫风面积 [m²]
R_rated = 12;          % 额定风速 [m/s]
omega_rated = 1500*2*pi/60;  % 额定转速 [rad/s] (1500 rpm)

% 额定转矩
Pn = 22e3;             % 额定功率 [W]
nn = 1500;             % 额定转速 [rpm]
wn = nn * 2*pi/60;     % 额定角速度 [rad/s]
Tn = Pn / wn;          % 额定转矩 [N·m]
T_max = 1.5 * Tn;      % 电机最大力矩 [N·m]

%% ==================== Cp(λ,β) 参数 ====================
%  Heier 模型拟合系数
c1 = 0.5176; c2 = 116; c3 = 0.4;
c4 = 5; c5 = 21; c6 = 0.0068;

%% ==================== 控制参数 ====================
%  变桨范围
beta_min = 0;          % 最小桨距角 [deg]
beta_max = 90;         % 最大桨距角 [deg]
beta_rate_max = 10;    % 最大变桨速率 [deg/s]

%  MPC 参数
Ts = 0.01;             % 控制周期 [s] (10ms)
Ts_current = 1e-4;     % 电流环采样周期 [s] (100μs)
Ts_speed   = 1e-3;     % 速度环采样周期 [s] (1ms)
Ts_outer   = 10e-3;    % 外环（桨距角）采样周期 [s] (10ms)
Ts_current = 1e-4;     % 电流环采样周期 [s] (100μs)
Ts_speed   = 1e-3;     % 速度环采样周期 [s] (1ms)
Ts_outer   = 10e-3;    % 外环（桨距角）采样周期 [s] (10ms)
Np = 20;               % 预测时域
Nc = 5;                % 控制时域

%  权重矩阵
Q_beta = 100;          % 桨距角跟踪权重
Q_sync = 50;           % 同步误差权重
R_delta = 0.1;         % 控制增量权重

%% ==================== 仿真参数 ====================
T_sim = 100;           % 仿真时长 [s]
dt = 1e-4;             % 仿真步长 [s]
V_ramp = 3;            % 阵风幅值 [m/s]
T_ramp_start = 20;     % 阵风起始时刻 [s]
T_ramp_dur = 10;       % 阵风持续时间 [s]

%% ==================== Cp 函数定义 ====================
Cp_fun = @(lambda, beta) c1*(c2./lambda - c3*beta - c4).*exp(-c5./lambda) + c6*lambda;

%% ==================== 状态空间初始条件 ====================
%  额定工作点
x0 = zeros(8,1);       % [id1,iq1,w1,theta1,id2,iq2,w2,theta2]

