# ========== 辅助函数 ==========
def add_section(title_text, level=1):
    h = doc.add_heading(title_text, level=level)
    for run in h.runs:
        run.font.color.rgb = RGBColor(0, 51, 102)
    return h

def add_subsection(title_text):
    p = doc.add_paragraph()
    run = p.add_run(f'▶ {title_text}')
    run.bold = True
    run.font.size = Pt(11)
    run.font.color.rgb = RGBColor(0, 80, 130)
    return p

def add_formula(label, formula, note=None):
    """添加公式块：标签 + 公式 + 可选说明"""
    p = doc.add_paragraph()
    run = p.add_run(f'{label}：')
    run.bold = True
    run.font.size = Pt(11)
    
    p2 = doc.add_paragraph()
    p2.paragraph_format.left_indent = Cm(1)
    run2 = p2.add_run(formula)
    run2.font.name = 'Cambria Math'
    run2.font.size = Pt(12)
    run2.font.color.rgb = RGBColor(0, 0, 139)
    
    if note:
        p3 = doc.add_paragraph()
        p3.paragraph_format.left_indent = Cm(1)
        run3 = p3.add_run(f'📌 {note}')
        run3.font.size = Pt(10)
        run3.font.color.rgb = RGBColor(100, 100, 100)
        run3.italic = True

def add_text(text, indent=0, bold=False, size=11):
    p = doc.add_paragraph()
    if indent:
        p.paragraph_format.left_indent = Cm(indent)
    run = p.add_run(text)
    run.font.size = Pt(size)
    if bold:
        run.bold = True
    return p

def add_param_table(headers, rows):
    """添加参数表"""
    table = doc.add_table(rows=1+len(rows), cols=len(headers))
    table.style = 'Light Grid Accent 1'
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    for i, h in enumerate(headers):
        cell = table.rows[0].cells[i]
        cell.text = h
        for p in cell.paragraphs:
            for r in p.runs:
                r.bold = True
                r.font.size = Pt(10)
    for ri, row in enumerate(rows):
        for ci, val in enumerate(row):
            cell = table.rows[ri+1].cells[ci]
            cell.text = str(val)
            for p in cell.paragraphs:
                for r in p.runs:
                    r.font.size = Pt(10)

