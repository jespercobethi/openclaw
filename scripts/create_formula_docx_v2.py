#   七、气动载荷模型
# ================================================================
add_section('七、气动载荷模型')

add_text('风轮从风中捕获的气动能量是变桨系统的负载来源，也是MPC需要处理的主要扰动。', 0.5)

add_formula('风轮气动转矩',
    'T_aero = (1/2)·ρ·π·R³·[Cp(β,λ)/λ]·V²',
    'ρ = 1.225 kg/m³（标准大气密度）。'
    '\n    R: 风轮半径 [m]（5MW风机典型值 63m）。'
    '\n    V: 来流风速 [m/s]。'
    '\n    Cp(β,λ): 风能利用系数（无量纲，理论最大值 16/27 ≈ 0.593，Betz极限）。')

add_formula('叶尖速比',
    'λ = ω_r · R / V',
    'ω_r: 风轮角速度 [rad/s]。'
    '\n    λ 反映叶片尖端线速度与风速之比，典型最优值 6~8。'
    '\n    λ 过小：叶片失速，效率低；λ 过大：阻力增大，效率也低。')

add_formula('Cp 经验公式（常用）',
    'Cp(β,λ) = 0.5176·(116/λi - 0.4β - 5)·exp(-21/λi) + 0.0068λ\n\n'
    '其中：1/λi = 1/(λ + 0.08β) - 0.035/(β³ + 1)',
    'λi 为等效叶尖速比，修正了桨距角的影响。'
    '\n    β = 0° 时 Cp 最大（约 0.48），β 增大 Cp 急剧下降。'
    '\n    变桨控制的本质：通过调节 β 来调节 Cp，从而控制气动功率。')

add_formula('气动功率',
    'P_aero = (1/2)·ρ·π·R²·Cp(β,λ)·V³',
    '功率与风速的三次方成正比，风速小幅变化会引起功率大幅波动。'
    '\n    额定风速以上通过增大 β 来降低 Cp，维持额定功率。')

add_formula('气动推力（轴向力）',
    'F_thrust = (1/2)·ρ·π·R²·Ct(β,λ)·V²',
    'Ct 为推力系数，Ct = 4a(1-a)，a 为轴向诱导因子。'
    '\n    推力影响塔架载荷，是结构设计的重要输入。')

add_formula('气动转矩折算到电机轴',
    'T_L = T_aero / (N·η)\n'
    '    = (1/2)·ρ·π·R³·[Cp/(λ·N·η)]·V²',
    '最终作为状态空间模型中的扰动项 d(k) 输入MPC。')

