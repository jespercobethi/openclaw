add_section('八、矢量控制与解耦（id = 0）')

add_text('矢量控制（FOC）是PMSM的标准控制策略，通过将三相电流分解为d轴和q轴分量，实现转矩的线性控制。id=0控制是最常用的策略。', 0.5)

add_subsection('8.1 前馈解耦')

add_formula('解耦电压方程',
    'u_d = u_d\' - ω_e·L_s·i_q\n'
    'u_q = u_q\' + ω_e·L_s·i_d + ω_e·ψ_f',
    "u_d', u_q' 为PI控制器的输出（不含耦合项）。"
    '\n    加入前馈补偿后，d轴和q轴完全解耦，可独立设计PI参数。'
    '\n    不解耦时：d轴和q轴电流会互相干扰，导致控制性能下降。')

add_subsection('8.2 电流环 PI 设计')

add_formula('电流环 PI 控制器',
    'u_d\' = Kp_i·(i_d_ref - i_d) + Ki_i·∫(i_d_ref - i_d)dt\n'
    'u_q\' = Kp_i·(i_q_ref - i_q) + Ki_i·∫(i_q_ref - i_q)dt',
    'Kp_i: 电流环比例增益，Ki_i: 电流环积分增益。'
    '\n    典型设计：将电流环整定为一阶系统，带宽 f_bw_i ≈ 1kHz。'
    '\n    Kp_i = L_s·ω_c，Ki_i = R·ω_c，其中 ω_c = 2π·f_bw_i。')

add_subsection('8.3 速度环 PI 设计')

add_formula('速度环 PI 控制器',
    'i_q_ref = Kp_ω·(ω_ref - ω_m) + Ki_ω·∫(ω_ref - ω_m)dt',
    '速度环输出作为q轴电流参考值。'
    '\n    速度环带宽应远小于电流环带宽（典型 1/10），避免相互干扰。'
    '\n    Kp_ω = J·ω_c_ω / K_t，Ki_ω = J·ω_c_ω² / (K_t·N_speed)，N_speed 为速度环衰减系数。')

add_formula('id=0 控制下的转矩关系',
    'T_e = K_t · i_q    （线性关系）',
    '当 id=0 时，所有电流都用于产生转矩，效率最高。'
    '\n    这是矢量控制的理论基础：控制 i_q 等效于控制转矩。')

