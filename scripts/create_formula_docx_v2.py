add_section('九、SVPWM 逆变器模型')

add_text('空间矢量脉宽调制（SVPWM）是将控制器输出的电压指令转换为逆变器开关信号的方法。在Simulink建模中需要用到。', 0.5)

add_formula('逆变器输出电压范围',
    'u_d_max = u_q_max = V_dc / √3\n\n'
    'V_dc: 直流母线电压（典型值 540V 或 600V）',
    'SVPWM 的线性调制区最大输出电压为 V_dc/√3。'
    '\n    超出此范围进入过调制区，输出电压波形失真。')

add_formula('电压矢量合成',
    'V_ref = (2/3)·(V_a + V_b·e^(j2π/3) + V_c·e^(j4π/3))',
    'SVPWM 将参考电压矢量 V_ref 分解为相邻两个基本矢量的加权合成。'
    '\n    一个PWM周期内切换3个基本矢量（含零矢量），实现平滑输出。')

add_formula('占空比计算（简化）',
    'T₁ = (√3·T_s/V_dc)·[V_α·sin(π/3-θ) - V_β·cos(π/3-θ)]\n'
    'T₂ = (√3·T_s/V_dc)·[-V_α·sin(θ) + V_β·cos(θ)]\n'
    'T₀ = T_s - T₁ - T₂',
    'T₁, T₂: 两个有效矢量的作用时间，T₀: 零矢量作用时间。'
    '\n    θ 为参考电压矢量的角度。')

