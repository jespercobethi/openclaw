add_section('十、MPC 滚动优化流程')

add_formula('MPC 算法步骤',
    '① 测量/估计当前状态 x(k)\n'
    '② 读取风速预测值 d(k) ~ d(k+N_p-1)（前馈）\n'
    '③ 求解 QP 优化问题 → 得到最优控制序列 U*\n'
    '④ 只执行第一步 u*(k)\n'
    '⑤ k←k+1，返回步骤①',
    'N_p = 20（预测时域），N_c = 5（控制时域）。'
    '\n    N_p > N_c 意味着只优化前 N_c 步控制量，后面保持不变。'
    '\n    每步都重新求解，实现"滚动"优化，具有天然的反馈校正能力。')

add_formula('MPC vs PID vs ADRC 对比',
    '┌─────────┬──────────────┬──────────────┬──────────────┐\n'
    '│ 特性     │ PID          │ ADRC         │ MPC          │\n'
    '├─────────┼──────────────┼──────────────┼──────────────┤\n'
    '│ 约束处理 │ 无法处理     │ 间接处理     │ 显式处理 ⭐  │\n'
    '│ 多目标   │ 需级联结构   │ 需级联结构   │ 统一目标函数 │\n'
    '│ 预测能力 │ 无           │ 无           │ N_p步预测 ⭐ │\n'
    '│ 计算量   │ 低           │ 中           │ 高（QP求解） │\n'
    '│ 模型依赖 │ 不依赖       │ 不依赖       │ 强依赖 ⭐    │\n'
    '│ 多电机同步│ 需额外补偿  │ 需偏差耦合   │ 目标函数嵌入 ⭐│\n'
    '└─────────┴──────────────┴──────────────┴──────────────┘',
    'MPC的核心优势：约束处理 + 预测 + 多目标统一优化。'
    '\n    MPC的核心劣势：计算量大 + 强依赖模型精度。')

