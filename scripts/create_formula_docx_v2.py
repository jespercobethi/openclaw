add_section('五、MPC 目标函数与约束处理')

add_text('MPC的核心思想：在每个采样时刻，求解一个有限时域优化问题，只执行最优控制的第一步，然后重新测量、重新优化（滚动优化）。', 0.5)

add_subsection('5.1 目标函数')

add_formula('MPC 目标函数（含同步误差）',
    'J = Σ_{i=1}^{N_p} [ Q·‖θ_pitch(k+i) - θ_ref(k+i)‖² ]\n'
    '  + Σ_{j=0}^{N_c-1} [ R·‖Δu(k+j)‖² ]\n'
    '  + Σ_{i=1}^{N_p} [ S·‖θ₁(k+i) - θ₂(k+i)‖² ]\n\n'
    '    ───────跟踪误差（第1项）───────  ─控制增量平滑（第2项）─  ─同步误差（第3项·创新）─',
    '第1项（跟踪）：桨距角跟踪参考值，Q 越大跟踪越快但可能振荡。'
    '\n    第2项（平滑）：抑制控制量剧烈变化，保护执行机构，R 越大越平滑。'
    '\n    第3项（同步）：两台电机桨距角之差，S 越大同步性越好（核心创新点）。'
    '\n    三者的权重平衡是MPC调参的关键。')

add_formula('权重参数选择指南',
    'Q（跟踪权重）：起步取 1~10，逐步增大直到跟踪误差满足要求。\n'
    'R（平滑权重）：起步取 0.1~1，逐步增大直到控制量变化率在执行机构允许范围内。\n'
    'S（同步权重）：起步取 5~20，确保同步误差小于允许值（如 0.1°）。\n\n'
    '调参顺序：先调 Q 和 R（单电机跟踪），再加 S（双电机同步）。',
    'Q/R 比值决定响应速度 vs 平滑性的权衡。'
    '\n    S/Q 比值决定同步精度 vs 跟踪精度的权衡。')

add_subsection('5.2 约束处理')

add_formula('控制量约束（硬约束）',
    'u_d_min ≤ u_d ≤ u_d_max\n'
    'u_q_min ≤ u_q ≤ u_q_max',
    '由逆变器直流母线电压决定：u_d_max ≈ u_q_max ≈ V_dc/√3。'
    '\n    超出约束范围时，MPC会自动寻找约束边界内的最优解。')

add_formula('状态量约束',
    '0° ≤ β ≤ 90°         （桨距角范围）\n'
    '-10°/s ≤ dβ/dt ≤ 10°/s  （桨距角变化率限制）\n'
    '0 ≤ ω_m ≤ ω_m_max     （电机转速上限）',
    '桨距角变化率限制保护变桨轴承和齿轮箱。'
    '\n    0° 对应满功率发电，90° 对应紧急顺桨（停机保护）。')

add_formula('增量约束',
    'Δu_min ≤ Δu(k) ≤ Δu_max\n'
    'Δu(k) = u(k) - u(k-1)',
    '限制每步控制量的最大变化幅度，等效于对控制量变化率的约束。'
    '\n    Δu_max 由逆变器开关频率和电机电流变化率决定。')

add_formula('QP 标准形式',
    'min   (1/2)·Uᵀ·H·U + fᵀ·U\n'
    's.t.  A_ineq·U ≤ b_ineq\n'
    '      U_min ≤ U ≤ U_max',
    'H = Θᵀ·Q̃·Θ + R̃  （海森矩阵，正定保证凸优化）\n'
    '    f = Θᵀ·Q̃·(Ψ·x(k) - X_ref) + ...  （梯度向量）\n'
    '    每个采样时刻在线求解一次QP，可用 quadprog/MPC Toolbox。')

